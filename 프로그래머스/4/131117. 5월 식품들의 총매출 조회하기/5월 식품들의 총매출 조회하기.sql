WITH TMP AS (
    SELECT PRODUCT_ID, DATE_FORMAT(PRODUCE_DATE, '%Y-%m') AS PRODUCE_MONTH, SUM(AMOUNT) AS AMOUNT_YEAR_MONTH
    FROM FOOD_ORDER
    WHERE DATE_FORMAT(PRODUCE_DATE, '%Y-%m') = '2022-05'
    GROUP BY PRODUCT_ID, DATE_FORMAT(PRODUCE_DATE, '%Y-%m')
)

SELECT PRODUCT_ID, PRODUCT_NAME, PRICE * AMOUNT_YEAR_MONTH AS TOTAL_SALES
FROM TMP
JOIN FOOD_PRODUCT
USING(PRODUCT_ID)
ORDER BY TOTAL_SALES DESC, PRODUCT_ID;
