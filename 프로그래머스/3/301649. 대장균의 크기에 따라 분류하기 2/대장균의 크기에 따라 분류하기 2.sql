WITH QUARTILE AS (
    SELECT
        ID,
        NTILE(4) OVER (ORDER BY SIZE_OF_COLONY DESC) AS QUARTILE_NUM
    FROM ECOLI_DATA
)

SELECT 
    ID,
    CASE QUARTILE_NUM
        WHEN 1 THEN 'CRITICAL'
        WHEN 2 THEN 'HIGH'
        WHEN 3 THEN 'MEDIUM'
        ELSE 'LOW'
    END AS COLONY_NAME
FROM QUARTILE
ORDER BY ID