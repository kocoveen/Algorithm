SELECT 
    YMT.YEAR,
    YMT.MAX_SIZE_YEAR - ED.SIZE_OF_COLONY AS YEAR_DEV,
    ID
FROM ECOLI_DATA AS ED
LEFT JOIN (
    SELECT 
        YEAR(DIFFERENTIATION_DATE) AS YEAR,
        MAX(SIZE_OF_COLONY) AS MAX_SIZE_YEAR
    FROM ECOLI_DATA
    GROUP BY YEAR(DIFFERENTIATION_DATE)
) AS YMT
ON YEAR(ED.DIFFERENTIATION_DATE) = YMT.YEAR
ORDER BY YMT.YEAR ASC, YEAR_DEV ASC